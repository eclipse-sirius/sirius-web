package org.eclipse.sirius.components.tables.tests.graphql;

import java.util.Objects;

import org.eclipse.sirius.components.collaborative.tables.dto.ResizeTableRowsInput;
import org.eclipse.sirius.components.graphql.tests.api.GraphQLResult;
import org.eclipse.sirius.components.graphql.tests.api.IGraphQLRequestor;
import org.eclipse.sirius.components.graphql.tests.api.IMutationRunner;
import org.springframework.stereotype.Service;

/**
 * Used to change several row heights with the GraphQL API.
 *
 * @author lfasani
 */
@Service
public class ResizeTableRowsMutationRunner implements IMutationRunner<ResizeTableRowsInput> {

    public static final String RESIZE_ROWS_MUTATION = """
                mutation resizeTableRows($input: ResizeTableRowsInput!) {
                  resizeTableRows(input: $input) {
                    __typename
                    ... on ErrorPayload {
                      messages {
                        body
                        level
                      }
                    }
                    ... on SuccessPayload {
                      messages {
                        body
                        level
                      }
                    }
                  }
                }
            """;

    private final IGraphQLRequestor graphQLRequestor;

    public ResizeTableRowsMutationRunner(IGraphQLRequestor graphQLRequestor) {
        this.graphQLRequestor = Objects.requireNonNull(graphQLRequestor);
    }

    @Override
    public GraphQLResult run(ResizeTableRowsInput input) {
        return this.graphQLRequestor.execute(RESIZE_ROWS_MUTATION, input);
    }
}
