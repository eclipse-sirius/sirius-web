package org.eclipse.sirius.components.view.form.provider.spec;

import java.util.Collection;

import org.eclipse.emf.common.notify.AdapterFactory;
import org.eclipse.sirius.components.view.form.FormFactory;
import org.eclipse.sirius.components.view.form.FormPackage;
import org.eclipse.sirius.components.view.form.provider.LabelDescriptionItemProvider;

/**
 * Customization of the item provider implementation generated by EMF.
 *
 * @author lfasani
 */
public class LabelDescriptionItemProviderSpec extends LabelDescriptionItemProvider {
    public LabelDescriptionItemProviderSpec(AdapterFactory adapterFactory) {
        super(adapterFactory);
    }

    @Override
    public Object getImage(Object object) {
        return this.overlayImage(object, this.getResourceLocator().getImage("full/obj16/LabelDescription.svg"));
    }

    @Override
    protected void collectNewChildDescriptors(Collection<Object> newChildDescriptors, Object object) {
        newChildDescriptors.add(this.createChildParameter(FormPackage.Literals.LABEL_DESCRIPTION__STYLE, FormFactory.eINSTANCE.createLabelDescriptionStyle()));

        newChildDescriptors.add(this.createChildParameter(FormPackage.Literals.LABEL_DESCRIPTION__CONDITIONAL_STYLES, FormFactory.eINSTANCE.createConditionalLabelDescriptionStyle()));
    }

}
